def log(msg: str) -> None:
    print(f"  [gen] {msg}", flush=True)


def run(cmd: list[str], **kwargs) -> None:
    subprocess.run([str(c) for c in cmd], check=True, **kwargs)


def need(tool: str, package: str) -> str:
    """Path of a host tool; installs its Debian package if it is missing (CI container)."""
    found = shutil.which(tool)
    if found:
        return found
    if shutil.which("apt-get") and hasattr(os, "geteuid") and os.geteuid() == 0:
        log(f"{tool} missing, installing {package}")
        subprocess.run(["apt-get", "update", "-qq"], check=False, stdout=subprocess.DEVNULL)
        subprocess.run(["apt-get", "install", "-y", "-qq", package], check=False, stdout=subprocess.DEVNULL)
        found = shutil.which(tool)
    if not found:
        raise SystemExit(f"gen_netsurf: '{tool}' is needed (package {package})")
    return found


# Perl randomises hash order on every run, and make-entities.pl builds its
# search tree in `keys %entities` order: without a fixed seed each build had a
# different entities.inc, so a rebuild of the same commit made a new binary.
PERL_ENV = {**os.environ, "PERL_HASH_SEED": "0", "PERL_PERTURB_KEYS": "0"}


def host_cc() -> str:
    return shutil.which("cc") or shutil.which("gcc") or need("gcc", "gcc")


# ── libcss ──────────────────────────────────────────────────────────────────

def gen_libcss(src: Path, gen: Path) -> None:
    props = src / "libs/libcss/src/parse/properties"
    tool = gen / "tools" / "css_property_parser_gen"
    tool.parent.mkdir(parents=True, exist_ok=True)
    run([host_cc(), "-O1", "-o", tool, props / "css_property_parser_gen.c"])
    count = 0
    for line in (props / "properties.gen").read_text().splitlines():
        m = re.match(r"^([^#][^:]+):", line)
        if not m:
            continue
        run([tool, "-o", props / f"autogenerated_{m.group(1)}.c", line.strip()], stdout=subprocess.DEVNULL)
        count += 1
    log(f"libcss: {count} property parsers")


# ── libhubbub / libparserutils ──────────────────────────────────────────────

def gen_hubbub(src: Path, gen: Path) -> None:
    lib = src / "libs/libhubbub"
    run([need("perl", "perl"), "build/make-entities.pl"], cwd=lib, stdout=subprocess.DEVNULL, env=PERL_ENV)
    out = gen / "hubbub" / "treebuilder" / "autogenerated-element-type.c"
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = out.with_suffix(".tmp")
    run([need("gperf", "gperf"), f"--output-file={tmp}", lib / "src/treebuilder/element-type.gperf"])
    text = tmp.read_text()
    tmp.unlink()
    # As the upstream Makefile's sed: the table is file-local.
    text = re.sub(r"^(const struct element_type_map)", r"static \1", text, flags=re.M)
    # gperf records the input path in #line directives; keep it out of the build.
    text = text.replace(str(lib) + "/", "")
    out.write_text(text)
    log("libhubbub: entities.inc, autogenerated-element-type.c")


def gen_parserutils(src: Path) -> None:
    run([need("perl", "perl"), "build/make-aliases.pl"], cwd=src / "libs/libparserutils", stdout=subprocess.DEVNULL,
        env=PERL_ENV)
    log("libparserutils: aliases.inc")


def gen_svgtiny(src: Path, gen: Path) -> None:
    """libsvgtiny's colour names (its Makefile's gperf and sed steps)."""
    lib = src / "libs/libsvgtiny"
    out = gen / "svgtiny" / "autogenerated_colors.c"
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = out.with_suffix(".tmp")
    run([need("gperf", "gperf"), f"--output-file={tmp}", lib / "src/colors.gperf"])
    text = tmp.read_text()
    tmp.unlink()
    text = re.sub(r"^(const struct svgtiny_named_color)", r"static \1", text, flags=re.M)
    text = text.replace(str(lib) + "/", "")  # #line directives name the input
    out.write_text(text)
    log("libsvgtiny: autogenerated_colors.c")


def gen_image_libs(src: Path, gen: Path) -> None:
    """The configuration headers libpng and libjpeg-turbo make with their
    configure/CMake steps, and their public headers in .papp-gen/include."""
    inc = gen / "include"
    inc.mkdir(parents=True, exist_ok=True)
    png = src / "libs/libpng"
    shutil.copyfile(png / "scripts/pnglibconf.h.prebuilt", inc / "pnglibconf.h")
    for name in ("png.h", "pngconf.h"):
        shutil.copyfile(png / name, inc / name)

    jpeg = src / "libs/libjpeg-turbo"
    cmake = (jpeg / "CMakeLists.txt").read_text()
    version = re.search(r"set\(VERSION ([0-9.]+)\)", cmake).group(1)
    major, minor, patch = (version.split(".") + ["0", "0"])[:3]
    # 8-bit samples, arithmetic decoding, no SIMD (none for RISC-V), the
    # libjpeg v6b API (JPEG_LIB_VERSION 62), as CMake's defaults.
    (inc / "jconfig.h").write_text(f"""/* Generated by ports/netsurf/gen_netsurf.py (libjpeg-turbo's jconfig.h.in). */
#define JPEG_LIB_VERSION  62
#define LIBJPEG_TURBO_VERSION  {version}
#define LIBJPEG_TURBO_VERSION_NUMBER  {int(major) * 1000000 + int(minor) * 1000 + int(patch)}
#define D_ARITH_CODING_SUPPORTED 1
#define MEM_SRCDST_SUPPORTED 1
#define BITS_IN_JSAMPLE  8
""")
    (inc / "jconfigint.h").write_text(f"""/* Generated by ports/netsurf/gen_netsurf.py (libjpeg-turbo's jconfigint.h.in). */
#define BUILD  "papp"
#undef inline
#define INLINE  __inline__ __attribute__((always_inline))
#define THREAD_LOCAL
#define PACKAGE_NAME  "libjpeg-turbo"
#define VERSION  "{version}"
#define SIZEOF_SIZE_T  4
#define HAVE_BUILTIN_CTZL
#if defined(__has_attribute)
#if __has_attribute(fallthrough)
#define FALLTHROUGH  __attribute__((fallthrough));
#else
#define FALLTHROUGH
#endif
#else
#define FALLTHROUGH
#endif
""")
    text = (jpeg / "jversion.h.in").read_text().replace("@COPYRIGHT_YEAR@", "1991-2023")
    (inc / "jversion.h").write_text(text)
    for name in ("jpeglib.h", "jmorecfg.h", "jerror.h"):
        shutil.copyfile(jpeg / name, inc / name)

    # libwebp's decoder: its public headers only (its own sources include
    # "src/..." from the checkout, which is not on the global include path:
    # libwebp's src/utils/ would shadow NetSurf's utils/).
    (inc / "webp").mkdir(exist_ok=True)
    for name in ("decode.h", "types.h"):
        shutil.copyfile(src / "libs/libwebp/src/webp" / name, inc / "webp" / name)
    log(f"image libraries: pnglibconf.h, libjpeg-turbo {version} configuration, libwebp headers")


