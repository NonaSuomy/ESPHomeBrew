#!/usr/bin/env python3
"""Prebuild step for the NetSurf PAPP (apps/psram_netsurf/papp.json).

NetSurf and its libraries generate some sources with host tools before they
compile. This does the same with the build machine's tools, inside the source
checkout that tools/build_papp.py prepared:

- libcss: the property parsers (css_property_parser_gen, from properties.gen)
- libhubbub: the entity table (make-entities.pl) and the element-type hash
  (gperf; written to .papp-gen/hubbub so the "*.c" group does not pick it up)
- libparserutils: the charset alias table (make-aliases.pl)
- NetSurf framebuffer frontend: the internal bitmap font (convert_font), the
  toolkit images (the PNG icons, pointers and throbber decoded here instead of
  with libpng, in convert_image's output format) and testament.h
- the resources NetSurf serves from resource: URLs and its Messages file,
  compiled in (papp_resources.c), so the app runs with nothing on the card
- libdom's hubbub binding headers as <dom/bindings/hubbub/...>

Everything is reproducible: no timestamps, host names or paths end up in the
output except what SOURCE_DATE_EPOCH gives.
"""

from __future__ import annotations

import argparse
import os
import re
import shutil
import struct
import subprocess
import sys
import time
import zlib
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
PORT = REPO / "ports" / "netsurf"


def log(msg: str) -> None:
    print(f"  [gen] {msg}", flush=True)


def run(cmd: list[str], **kwargs) -> None:
    subprocess.run([str(c) for c in cmd], check=True, **kwargs)


def need(tool: str, package: str) -> str:
    """Path of a host tool; installs its Debian package if it is missing (CI container)."""
    found = shutil.which(tool)
    if found:
        return found
    if shutil.which("apt-get") and hasattr(os, "geteuid") and os.geteuid() == 0:
        log(f"{tool} missing, installing {package}")
        subprocess.run(["apt-get", "update", "-qq"], check=False, stdout=subprocess.DEVNULL)
        subprocess.run(["apt-get", "install", "-y", "-qq", package], check=False, stdout=subprocess.DEVNULL)
        found = shutil.which(tool)
    if not found:
        raise SystemExit(f"gen_netsurf: '{tool}' is needed (package {package})")
    return found


def host_cc() -> str:
    return shutil.which("cc") or shutil.which("gcc") or need("gcc", "gcc")


# ── libcss ──────────────────────────────────────────────────────────────────

def gen_libcss(src: Path, gen: Path) -> None:
    props = src / "libs/libcss/src/parse/properties"
    tool = gen / "tools" / "css_property_parser_gen"
    tool.parent.mkdir(parents=True, exist_ok=True)
    run([host_cc(), "-O1", "-o", tool, props / "css_property_parser_gen.c"])
    count = 0
    for line in (props / "properties.gen").read_text().splitlines():
        m = re.match(r"^([^#][^:]+):", line)
        if not m:
            continue
        run([tool, "-o", props / f"autogenerated_{m.group(1)}.c", line.strip()], stdout=subprocess.DEVNULL)
        count += 1
    log(f"libcss: {count} property parsers")


# ── libhubbub / libparserutils ──────────────────────────────────────────────

def gen_hubbub(src: Path, gen: Path) -> None:
    lib = src / "libs/libhubbub"
    run([need("perl", "perl"), "build/make-entities.pl"], cwd=lib, stdout=subprocess.DEVNULL)
    out = gen / "hubbub" / "treebuilder" / "autogenerated-element-type.c"
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = out.with_suffix(".tmp")
    run([need("gperf", "gperf"), f"--output-file={tmp}", lib / "src/treebuilder/element-type.gperf"])
    text = tmp.read_text()
    tmp.unlink()
    # As the upstream Makefile's sed: the table is file-local.
    text = re.sub(r"^(const struct element_type_map)", r"static \1", text, flags=re.M)
    # gperf records the input path in #line directives; keep it out of the build.
    text = text.replace(str(lib) + "/", "")
    out.write_text(text)
    log("libhubbub: entities.inc, autogenerated-element-type.c")


def gen_parserutils(src: Path) -> None:
    run([need("perl", "perl"), "build/make-aliases.pl"], cwd=src / "libs/libparserutils", stdout=subprocess.DEVNULL)
    log("libparserutils: aliases.inc")


def gen_dom_headers(src: Path, gen: Path) -> None:
    out = gen / "include" / "dom" / "bindings" / "hubbub"
    out.mkdir(parents=True, exist_ok=True)
    for name in ("parser.h", "errors.h"):
        shutil.copyfile(src / "libs/libdom/bindings/hubbub" / name, out / name)


# ── Framebuffer font ────────────────────────────────────────────────────────

def gen_font(src: Path, gen: Path) -> None:
    tool = gen / "tools" / "convert_font"
    run([host_cc(), "-O1", "-o", tool, src / "tools/convert_font.c"])
    run([tool, "-q", "-H", gen / "font-ns-sans.h",
         src / "frontends/framebuffer/res/fonts/glyph_data", gen / "font-ns-sans.c"], stdout=subprocess.DEVNULL)
    log("font: font-ns-sans.c")


