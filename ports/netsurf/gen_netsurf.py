def c_bytes(name: str, data: bytes) -> list[str]:
    lines = [f"static const uint8_t {name}[{len(data) + 1}] = {{"]
    for i in range(0, len(data), 24):
        lines.append("\t" + ",".join(str(v) for v in data[i:i + 24]) + ",")
    lines.append("\t0\n};")  # NUL-terminated: some consumers treat it as a string
    return lines


def fat_messages(src: Path, lang: str = "en", platform: str = "fb") -> bytes:
    """tools/split-messages.pl -l en -p fb, as plain "key:value" lines."""
    out: dict[str, str] = {}
    pattern = re.compile(r"^([a-z]{2}(?:_[A-Z]{2})?).([^.]+).([^:]+):(.*)")
    for line in (src / "resources/FatMessages").read_text(encoding="utf-8").splitlines():
        if line.startswith("#") or not line.strip():
            continue
        m = pattern.match(line)
        if not m:
            continue
        lng, plat, key, value = m.groups()
        if lng == lang and plat in ("all", platform):
            out[key] = value
    return "".join(f"{k}:{v}\n" for k, v in out.items()).encode("utf-8")


