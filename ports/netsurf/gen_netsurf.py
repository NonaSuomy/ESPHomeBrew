def png_rgba(data: bytes) -> tuple[int, int, bytes]:
    """Decode a PNG to 8-bit RGBA (what convert_image asks libpng for)."""
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("not a PNG")
    pos, idat, plte, trns = 8, b"", b"", None
    width = height = depth = ctype = interlace = 0
    while pos < len(data):
        length, kind = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + length]
        pos += 12 + length
        if kind == b"IHDR":
            width, height, depth, ctype, _, _, interlace = struct.unpack(">IIBBBBB", body)
        elif kind == b"PLTE":
            plte = body
        elif kind == b"tRNS":
            trns = body
        elif kind == b"IDAT":
            idat += body
        elif kind == b"IEND":
            break
    if interlace:
        raise ValueError("interlaced PNGs are not supported")
    channels = {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}[ctype]
    bits = channels * depth
    stride = (width * bits + 7) // 8
    bpp = max(1, bits // 8)
    raw = zlib.decompress(idat)
    rows: list[bytearray] = []
    prev = bytearray(stride)
    at = 0
    for _ in range(height):
        kind = raw[at]
        line = bytearray(raw[at + 1:at + 1 + stride])
        at += 1 + stride
        for i in range(stride):
            a = line[i - bpp] if i >= bpp else 0
            b = prev[i]
            c = prev[i - bpp] if i >= bpp else 0
            if kind == 1:
                line[i] = (line[i] + a) & 0xFF
            elif kind == 2:
                line[i] = (line[i] + b) & 0xFF
            elif kind == 3:
                line[i] = (line[i] + (a + b) // 2) & 0xFF
            elif kind == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                pred = a if pa <= pb and pa <= pc else (b if pb <= pc else c)
                line[i] = (line[i] + pred) & 0xFF
        rows.append(line)
        prev = line

    def samples(line: bytearray) -> list[int]:
        if depth == 8:
            return list(line)
        if depth == 16:
            return [line[i] for i in range(0, len(line), 2)]  # strip to 8 bits
        per = 8 // depth
        mask = (1 << depth) - 1
        out = []
        for byte in line:
            for k in range(per):
                out.append((byte >> (8 - depth * (k + 1))) & mask)
        return out

    out = bytearray()
    for line in rows:
        s = samples(line)
        for x in range(width):
            if ctype == 3:
                idx = s[x]
                r, g, b = plte[idx * 3:idx * 3 + 3]
                a = trns[idx] if trns is not None and idx < len(trns) else 255
            elif ctype == 0:
                v = s[x]
                if depth < 8:
                    v = v * 255 // ((1 << depth) - 1)
                r = g = b = v
                a = 0 if trns is not None and s[x] == (struct.unpack(">H", trns[:2])[0] >> (8 if depth == 16 else 0)) else 255
            elif ctype == 2:
                r, g, b = s[x * 3:x * 3 + 3]
                a = 255
                if trns is not None and len(trns) >= 6:
                    key = tuple(v >> (8 if depth == 16 else 0) for v in struct.unpack(">HHH", trns[:6]))
                    if (r, g, b) == key:
                        a = 0
            elif ctype == 4:
                r = g = b = s[x * 2]
                a = s[x * 2 + 1]
            else:
                r, g, b, a = s[x * 4:x * 4 + 4]
            out += bytes((r, g, b, a))
    return width, height, bytes(out)


def gen_images(src: Path, gen: Path) -> None:
    res = src / "frontends/framebuffer/res"
    for name, rel in FB_IMAGES.items():
        path = res / rel
        if not path.exists() and rel.startswith("throbber/"):
            path = src / "resources" / rel  # the framebuffer res/throbber files are symlinks to these
        w, h, px = png_rgba(path.read_bytes())

        def at(x: int, y: int) -> bytes:
            return px[(y * w + x) * 4:(y * w + x) * 4 + 4]

        # convert_image's detect_hotspot (its R/B byte offsets are swapped,
        # which does not matter for the pure-green marker pixels it looks for).
        cursor, greens, hot_x, hot_y = True, 0, 0, 0
        for i in range(w):
            r, g, b, a = at(i, 0)
            if a == 255:
                if g == 255:
                    greens, hot_x = greens + 1, i
                if r != 0 or b != 0:
                    cursor = False
                    break
            elif a != 0:
                cursor = False
                break
        if cursor and greens != 1:
            cursor = False
        if cursor:
            for i in range(h):
                r, g, b, a = at(0, i)
                if a == 255:
                    if g == 255:
                        greens, hot_y = greens + 1, i
                    if r != 0 or b != 0:
                        cursor = False
                        break
                elif a != 0:
                    cursor = False
                    break
            if cursor and greens != 2:
                cursor = False
        ow, oh = (w - 1, h - 1) if cursor else (w, h)
        ox = 1 if cursor else 0
        lines = [f"/* Generated from {rel} by ports/netsurf/gen_netsurf.py. */",
                 "#include <sys/types.h>", "#include <stdint.h>", "#include <stdbool.h>",
                 "#include <libnsfb.h>", '#include "netsurf/plot_style.h"',
                 '#include "framebuffer/gui.h"', '#include "framebuffer/fbtk.h"', "",
                 f"static uint8_t {name}_pixdata[] = {{"]
        for y in range(oh):
            row = b"".join(at(x + ox, y + ox) for x in range(ow))
            lines.append("\t" + " ".join(f"0x{v:02x}," for v in row))
        lines += ["};", "", f"struct fbtk_bitmap {name} = {{",
                  f"\t.width\t\t= {ow},", f"\t.height\t\t= {oh},",
                  f"\t.hot_x\t\t= {hot_x - 1 if cursor else 0},", f"\t.hot_y\t\t= {hot_y - 1 if cursor else 0},",
                  f"\t.pixdata\t= {name}_pixdata,", "};", ""]
        (gen / f"image-{name}.c").write_text("\n".join(lines))
    log(f"images: {len(FB_IMAGES)} toolkit bitmaps")


# ── testament.h ─────────────────────────────────────────────────────────────

def gen_testament(src: Path, gen: Path) -> None:
    rev = subprocess.run(["git", "rev-parse", "HEAD"], cwd=src, capture_output=True, text=True).stdout.strip()
    epoch = int(os.environ.get("SOURCE_DATE_EPOCH", "0"))
    date = time.strftime("%d.%m.%Y", time.gmtime(epoch))
    (gen / "testament.h").write_text(f"""/* Generated by ports/netsurf/gen_netsurf.py (tools/git-testament.pl's format). */
#ifndef NETSURF_REVISION_TESTAMENT
#define NETSURF_REVISION_TESTAMENT "{rev}"
#define USERNAME "papp"
#define GECOS "PAPP build"
#define WT_ROOT "/papp-src"
#define WT_HOSTNAME "papp-conversions"
#define WT_COMPILEDATE "{date}"
#define CI_BUILD "PAPP"
#define WT_BRANCHPATH "master"
#define WT_BRANCHISMASTER 1
#define WT_REVID "{rev}"
#define WT_MODIFIED 0
#define WT_MODIFICATIONS {{ \\
}}
#endif
""")


