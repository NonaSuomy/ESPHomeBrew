def gen_fonts(src: Path, gen: Path) -> None:
    fonttools = src / "libs/fonttools/Lib"
    env = {**os.environ, "PYTHONPATH": str(fonttools), "PYTHONHASHSEED": "0", "PYTHONDONTWRITEBYTECODE": "1"}
    out = gen / "fonts"
    out.mkdir(parents=True, exist_ok=True)
    lines = ["/* Generated by ports/netsurf/gen_netsurf.py: DejaVu fonts, cut down (see FONTS there). */",
             "#include <stddef.h>", "#include <stdint.h>", '#include "papp_fonts.h"', ""]
    table = []
    total_in = total_out = 0
    for i, name in enumerate(FONTS):
        font = src / FONT_DIR / name
        subset = out / name
        run([sys.executable, "-m", "fontTools.subset", font, f"--output-file={subset}",
             f"--unicodes={FONT_CHARS}", "--no-hinting", "--layout-features=", "--notdef-outline",
             "--drop-tables+=GSUB,GPOS,GDEF,kern,FFTM", "--name-IDs=0,1,2,3,4,5,6,13,14", "--no-recalc-timestamp"],
            env=env, stdout=subprocess.DEVNULL)
        data = subset.read_bytes()
        total_in += font.stat().st_size
        total_out += len(data)
        lines += c_bytes(f"font_{i}", data) + [""]
        table.append(f'\t{{"{name}", font_{i}, {len(data)}}},')
    shutil.rmtree(out)
    lines += ["const struct papp_font papp_fonts[] = {", *table, "\t{NULL, NULL, 0}", "};", ""]
    (gen / "papp_fonts.c").write_text("\n".join(lines))
    log(f"fonts: {len(FONTS)} DejaVu fonts, {total_in} bytes cut down to {total_out}")


