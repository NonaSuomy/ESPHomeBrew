def html_text(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def port_licences(src: Path) -> str:
    parts = ['<h2 class="ns-border">Added by the PAPP port</h2>\n',
             "<p>This build of NetSurf also contains the following, under these licences.</p>\n"]
    for name, url, note, rel in PORT_LICENCES:
        text = (src / rel).read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").strip("\n")
        parts.append(f'<h3><a href="{url}">{name}</a></h3>\n')
        if note:
            parts.append(f"<p>{note}</p>\n")
        parts.append(f"<pre>{html_text(text)}</pre>\n")
    return "".join(parts)


def gen_resources(src: Path, gen: Path) -> None:
    lines = ["/* Generated by ports/netsurf/gen_netsurf.py: NetSurf's resources, compiled in. */",
             "#include <stddef.h>", "#include <stdint.h>", '#include "papp_resources.h"', ""]
    table = []
    for i, (name, rel) in enumerate(RESOURCES.items()):
        path = REPO / rel[len("local:"):] if rel.startswith("local:") else src / rel
        data = path.read_bytes()
        if name == "licence.html":
            marker = b'<div class="footer'
            if marker not in data:
                raise SystemExit("gen_netsurf: licence.html has no footer to put the port's licences before")
            data = data.replace(marker, port_licences(src).encode("utf-8") + b"\n" + marker, 1)
        lines += c_bytes(f"res_{i}", data) + [""]
        table.append(f'\t{{"{name}", res_{i}, {len(data)}}},')
    messages = fat_messages(src)
    lines += c_bytes("messages", messages) + [""]
    lines += ["const struct papp_resource papp_resources[] = {", *table, "\t{NULL, NULL, 0}", "};", "",
              "const uint8_t *const papp_messages = messages;",
              f"const size_t papp_messages_len = {len(messages)};", ""]
    (gen / "papp_resources.c").write_text("\n".join(lines))
    log(f"resources: {len(RESOURCES)} files, Messages {len(messages)} bytes")


def lint(units_path: Path) -> None:
    """Show the compiler's warnings for the port's own code and the patched
    NetSurf files (the build only reports errors). Never fails the build."""
    import json
    units = json.loads(units_path.read_text())
    patched = ("frontends/framebuffer/gui.c", "frontends/framebuffer/fetch.c", "content/fetch.c",
               "frontends/framebuffer/fbtk/text.c", "frontends/framebuffer/fbtk/event.c",
               "content/fetchers/about/query_privacy.c", "content/handlers/image/png.c",
               "content/handlers/image/jpeg.c", "frontends/framebuffer/framebuffer.c",
               "frontends/framebuffer/fbtk/fbtk.c", "frontends/framebuffer/fbtk/osk.c",
               "content/fetchers/about/about.c", "desktop/hotlist.c", "content/handlers/image/svg.c",
               "content/handlers/image/webp.c")
    serious = re.compile(r"implicit|incompatible|int-conversion|return-mismatch|uninitialized|overflow|"
                         r"array-bounds|format|sign-compare|unused-variable")
    checked = shown = 0
    for unit in units:
        src = unit["src"].replace("\\", "/")
        own = "/ports/netsurf/" in src
        if not own and not src.endswith(patched):
            continue
        checked += 1
        result = subprocess.run([unit["compiler"], *unit["flags"], "-Wall", "-Wextra", "-Wno-unused-parameter",
                                 "-Wno-sign-compare", "-fsyntax-only", unit["src"]],
                                capture_output=True, text=True)
        lines = [l for l in result.stderr.splitlines() if "warning:" in l or "error:" in l]
        if not own:
            lines = [l for l in lines if serious.search(l) and "/ports/netsurf/" not in l]
        for line in lines[:20]:
            log("lint: " + re.sub(r"^\S*/(ports/netsurf/|src-[^/]+/)", "", line)[:240])
        shown += len(lines)
    log(f"lint: {checked} files checked, {shown} warnings")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--src", type=Path, required=True)
    parser.add_argument("--gen", type=Path, required=True)
    parser.add_argument("--units", type=Path)
    args = parser.parse_args()
    src, gen = args.src.resolve(), args.gen.resolve()
    gen.mkdir(parents=True, exist_ok=True)
    log(f"host cc: {shutil.which('cc') or shutil.which('gcc') or 'none'}, perl: {shutil.which('perl') or 'none'}, "
        f"gperf: {shutil.which('gperf') or 'none'}")
    gen_libcss(src, gen)
    gen_hubbub(src, gen)
    gen_parserutils(src)
    gen_svgtiny(src, gen)
    gen_dom_headers(src, gen)
    gen_image_libs(src, gen)
    gen_expat(src, gen)
    gen_fonts(src, gen)
    gen_images(src, gen)
    gen_testament(src, gen)
    gen_resources(src, gen)
    shutil.rmtree(gen / "tools", ignore_errors=True)
    if args.units is not None:
        lint(args.units)
    return 0


