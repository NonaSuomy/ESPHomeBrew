#!/usr/bin/env python3
"""Prebuild step for the NetSurf PAPP (apps/netsurf/papp.json).

NetSurf and its libraries generate some sources with host tools before they
compile. This does the same with the build machine's tools, inside the source
checkout that tools/build_papp.py prepared:

- libcss: the property parsers (css_property_parser_gen, from properties.gen)
- libhubbub: the entity table (make-entities.pl) and the element-type hash
  (gperf; written to .papp-gen/hubbub so the "*.c" group does not pick it up)
- libparserutils: the charset alias table (make-aliases.pl)
- libsvgtiny: the colour name hash (gperf; .papp-gen/svgtiny, which
  svgtiny_parse.c includes)
- NetSurf framebuffer frontend: the toolkit images (the PNG icons, pointers
  and throbber decoded here instead of with libpng, in convert_image's output
  format) and testament.h
- the fonts: subsets of the DejaVu fonts (fontTools' subsetter, run from its
  pinned checkout), compiled in (papp_fonts.c)
- the resources NetSurf serves from resource: URLs and its Messages file,
  compiled in (papp_resources.c), so the app runs with nothing on the card;
  licence.html also gets the licences of the fonts and the libraries 0.3
  added
- libdom's hubbub and XML binding headers as <dom/bindings/...>
- libpng's pnglibconf.h (its prebuilt default), libjpeg-turbo's
  jconfig.h/jconfigint.h/jversion.h (what its CMake step would write) and
  expat's expat_config.h, with the public headers of those, libwebp's decoder
  and expat in .papp-gen/include

With --units it then prints the compiler's warnings for the port's own
files and the patched NetSurf files (the build itself only shows errors).

Everything is reproducible: no timestamps, host names or paths end up in the
output except what SOURCE_DATE_EPOCH gives.
"""

